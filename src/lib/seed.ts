/**
 * دفتر اليومية الأصلي — مشروع الحلال
 * من 12 أغسطس 2026 إلى 14 نوفمبر 2026 (18 قيداً، المجموع 297,938 ريال)
 * منقول حرفياً من ملف daftar_alyawmiya.pdf — يُعرض للمراجعة قبل الاستيراد.
 */

type L = [accountId: string, riyal: number, note?: string]

function entry(number: number, date: string, description: string, debits: L[], flagNote?: string): EntryDraft {
  const lines: EntryLine[] = debits.map(([accountId, r, note]) => ({ accountId, debit: Math.round(r * 100), credit: 0, note }))
  const total = lines.reduce((s, l) => s + l.debit, 0)
  lines.push({ accountId: CASH_ID, debit: 0, credit: total })
  const main = [...lines].sort((a, b) => b.debit - a.debit)[0]
  return {
    number,
    date,
    description,
    type: new Set(debits.map((d) => d[0])).size > 1 ? 'compound' : guessOperation(main.accountId, CASH_ID),
    lines,
    ...(flagNote ? { flagged: true, flagNote } : {}),
  }
}

